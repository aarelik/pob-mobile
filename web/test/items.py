#!/usr/bin/env python3
"""Item editing at a phone viewport: paste an item into Ring 1, check the stats
move, pick a unique, edit an item's text, unequip."""
import os, sys
from playwright.sync_api import sync_playwright
url = sys.argv[1]; code = open(sys.argv[2]).read().strip(); ring = open(sys.argv[3]).read()
out = os.path.join(os.path.dirname(__file__), "screens"); os.makedirs(out, exist_ok=True)
errors = []
shot = lambda pg, n: (pg.screenshot(path=os.path.join(out, f"{n}.png")), print("  screenshot", n))
strip = lambda pg: " | ".join(pg.locator(".strip .cell").nth(i).inner_text().replace("\n", " ") for i in range(4))
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg = ctx.new_page()
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("console", lambda m: m.type == "error" and errors.append(m.text))
    pg.goto(url)
    pg.get_by_role("heading", name="Builds").wait_for(timeout=60000)
    pg.get_by_role("button", name="Import").first.click(); pg.locator("textarea").fill(code)
    pg.get_by_role("dialog").get_by_role("button", name="Import").click()
    pg.get_by_text("Main skill").wait_for(timeout=60000)
    pg.locator("nav").get_by_role("button", name="Items").click(); pg.wait_for_timeout(800)
    shot(pg, "i1-items")
    print("before:", strip(pg))
    dlg = pg.get_by_role("dialog")
    pg.locator(".slot", has_text="Ring 1").click()
    dlg.locator(".tt").wait_for(timeout=10000)
    shot(pg, "i2-ring-sheet")
    dlg.get_by_role("button", name="Change").click()
    dlg.get_by_role("button", name="Paste", exact=True).first.click()
    dlg.locator("textarea").fill(ring)
    dlg.locator(".prev .tt").wait_for(timeout=10000); pg.wait_for_timeout(300)
    shot(pg, "i3-paste-preview")
    dlg.get_by_role("button", name="Equip in Ring 1").click()
    pg.get_by_text("Item added and equipped").wait_for(timeout=15000); pg.wait_for_timeout(800)
    print("after paste:", strip(pg))
    shot(pg, "i4-equipped")
    # Uniques
    dlg.get_by_role("button", name="Change").click()
    dlg.get_by_role("button", name="Uniques").click()
    dlg.get_by_placeholder("Search uniques").fill("kikazaru")
    dlg.locator(".pick", has_text="Kikazaru").wait_for(timeout=30000)
    dlg.locator(".pick", has_text="Kikazaru").click()
    dlg.locator(".tt").wait_for(timeout=10000); pg.wait_for_timeout(300)
    shot(pg, "i5-unique-preview")
    dlg.get_by_role("button", name="Equip in Ring 1").click()
    pg.get_by_text("Equipped Kikazaru").wait_for(timeout=15000); pg.wait_for_timeout(600)
    print("after unique:", strip(pg), "| slot:", pg.locator(".slot", has_text="Ring 1").inner_text().replace("\n", " "))
    # Edit text
    dlg.get_by_role("button", name="Edit").click()
    ed = pg.get_by_role("dialog", name="Craft item")
    ed.get_by_role("button", name="Text").click()
    t = ed.locator("textarea").input_value()
    ed.locator("textarea").fill(t + "\n+50 to maximum Life")
    pg.wait_for_timeout(300)
    shot(pg, "i6-edit")
    ed.get_by_role("button", name="Save text").click(); pg.wait_for_timeout(2500)
    print("after edit (+50 life):", strip(pg))
    ed.get_by_role("button", name="Close").click(); pg.wait_for_timeout(500)
    dlg.get_by_role("button", name="Unequip").click()
    pg.get_by_text("Unequipped").wait_for(timeout=15000); pg.wait_for_timeout(600)
    print("after unequip:", strip(pg), "| slot:", pg.locator(".slot", has_text="Ring 1").inner_text().replace("\n", " "))
    pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
    shot(pg, "i7-after")
    b.close()
print("errors:", errors or "none")
sys.exit(1 if errors else 0)
